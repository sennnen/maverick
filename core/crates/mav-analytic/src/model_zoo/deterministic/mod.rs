//! The half of the zoo that runs as Rust rather than as a converted artefact.
//!
//! Twelve of the thirty-one training archives contain no weights at all. They are
//! TorchScript because that is what the training pipeline emits, but what they hold is
//! arithmetic: threshold tables, weighted averages, medians, scaling curves. There is no
//! tensor for an accelerator to accelerate.
//!
//! So they are not converted. [`super`] explains why the neural cores go to Core ML and
//! TensorFlow Lite; the same reasoning sends these the other way. Shipping a weighted
//! average as an `.mlpackage` would add a platform runtime, an FFI round trip and an
//! artefact hash to guard, in exchange for nothing — and it would put the arithmetic
//! somewhere neither platform can golden-vector test it.
//!
//! Each module here is a faithful port of one archive, with the exact tables and the exact
//! branch order, tested against vectors generated from the archive itself. Where the
//! original computes in a narrower precision than its inputs, the port reproduces that
//! too: matching the reference matters more than being tidy.
//!
//! All twelve are ported: [`astd_event_detection`], [`atlas_trendline`],
//! [`cumulative_stress`], [`cva_calibrator`], [`daily_medians`], [`daytime_stress`],
//! [`meal_timing`], [`pregnancy_biometrics`], [`short_term_baselines`],
//! [`steps_motion_decoder`], [`stress_resilience`], [`training_stress_score`].
//!
//! [`atlas`] is here too and is the exception that proves the rule: it *does* hold weights —
//! sixty of them, across twelve linear regressions. Sixty coefficients in dot products of at
//! most five terms is not work an accelerator can help with, so the same reasoning applies
//! and it takes the same route.
//!
//! Each port's golden vectors live in `artifacts/models/vectors/` and are generated by
//! `tools/ml/deterministic_vectors.py`, which runs the archive itself. Regenerate them
//! there rather than editing them; see docs/testing.md.


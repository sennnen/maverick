/// The median as `torch.median` computes it: for an even count, the lower of the two
/// middle values rather than their mean.
///
/// Every port here needs it, and getting it wrong shifts a baseline by half a step on
/// exactly the even-length inputs a short history produces.
pub(crate) fn torch_median(values: &[f64]) -> Option<f64> {
    if values.is_empty() {
        return None;
    }
    let mut sorted: Vec<f64> = values.to_vec();
    sorted.sort_by(|a, b| a.partial_cmp(b).unwrap_or(core::cmp::Ordering::Equal));
    Some(sorted[(sorted.len() - 1) / 2])
}

/// The median as NumPy computes it: for an even count, the mean of the two middle values.
///
/// Two archives want this one instead, and both reach it the same roundabout way — taking
/// `torch.median` of the values, again with the maximum appended, and averaging the two.
/// Appending the maximum shifts an even-length input's lower-middle up to the upper-middle,
/// so the average of the two calls is the average of the middle pair. The port computes it
/// directly; the identity is why the two agree.
pub(crate) fn numpy_median(values: &[f64]) -> Option<f64> {
    if values.is_empty() {
        return None;
    }
    let mut sorted: Vec<f64> = values.to_vec();
    sorted.sort_by(|a, b| a.partial_cmp(b).unwrap_or(core::cmp::Ordering::Equal));
    let middle = sorted.len() / 2;
    if sorted.len() % 2 == 1 {
        Some(sorted[middle])
    } else {
        Some((sorted[middle - 1] + sorted[middle]) / 2.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn median_of_an_odd_count_is_the_middle_value() {
        assert_eq!(torch_median(&[53.0, 54.0, 55.0, 56.0, 57.0]), Some(55.0));
    }

    #[test]
    fn median_of_an_even_count_is_the_lower_middle_not_the_mean() {
        // The mean of the middle pair would be 55.0. torch.median returns 54.0, and a
        // baseline that used the mean would drift from the reference on every even history.
        assert_eq!(torch_median(&[53.0, 54.0, 56.0, 57.0]), Some(54.0));
    }

    #[test]
    fn median_of_nothing_is_nothing() {
        assert_eq!(torch_median(&[]), None);
    }
}
